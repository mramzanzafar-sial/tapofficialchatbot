/* ---------- اردو ٹیکسٹ نارملائزیشن ---------- */
function normalize(text) {
  return (text || "")
    .replace(/[ً-ٰٟ]/g, "")          // اعراب / تشکیلات ہٹائیں
    .replace(/[ي]/g, "ی")            // عربی ی → اردو ی
    .replace(/[ك]/g, "ک")            // عربی ک → اردو ک
    .replace(/ة/g, "ہ")              // ة → ہ
    .replace(/[أإآ]/g, "ا")          // ہمزہ کی شکلیں → ا
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ی")
    .replace(/[«»""''„‚]/g, " ")     // اقتباسی علامات
    .replace(/[.,;:!?؟۔،\-\–—()\[\]{}*•·|/\\@#$%^&+=~`<>]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function tokens(text) {
  return normalize(text).split(" ").filter(function (t) { return t.length > 0; });
}

