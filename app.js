/* ---------- خصوصی ہینڈلرز ---------- */
var GREETINGS = ["سلام", "السلام علیکم", "آداب", "ہیلو", "hello", "hi", "aoa"];
var THANKS = ["شکریہ", "مہربانی", "جزاک", "thanks", "thank"];
var BYE = ["خدا حافظ", "اللہ حافظ", "الوداع", "bye"];

function isGreeting(nq) {
  var t = tokens(nq);
  return GREETINGS.some(function (g) {
    var ng = normalize(g);
    return t.indexOf(ng) !== -1 || nq === ng;
  });
}

function isThanks(nq) {
  return THANKS.some(function (w) { return nq.indexOf(normalize(w)) !== -1; });
}

function isBye(nq) {
  return BYE.some(function (w) { return nq.indexOf(normalize(w)) !== -1; });
}

/* صوبے کی شناخت */
var PROVINCES = [
  { keys: ["پنجاب"], id: "punjab" },
  { keys: ["خیبر", "پختونخوا"], id: "kpk" },
  { keys: ["سندھ"], id: "sindh" },
  { keys: ["بلوچستان"], id: "balochistan" },
  { keys: ["کشمیر", "جموں"], id: "kashmir" },
  { keys: ["گلگت", "بلتستان"], id: "gilgit" }
];

function detectProvince(nq) {
  for (var i = 0; i < PROVINCES.length; i++) {
    var pr = PROVINCES[i];
    for (var j = 0; j < pr.keys.length; j++) {
      if (nq.indexOf(normalize(pr.keys[j])) !== -1) return pr.id;
    }
  }
  return null;
}

function kbById(id) {
  for (var i = 0; i < KB.length; i++) if (KB[i].id === id) return KB[i];
  return null;
}

/* ---------- اسکورنگ میچر (لمبے کلیدی الفاظ = زیادہ مخصوص) ---------- */
function scoreSection(sec, nq) {
  var score = 0;
  for (var i = 0; i < sec.keys.length; i++) {
    var k = normalize(sec.keys[i]);
    if (!k) continue;
    if (nq === k) score += 50;
    else if (nq.indexOf(k) !== -1) score += k.length;
  }
  return score;
}

var FALLBACK = "معذرت، یہ معلومات میرے پاس موجود دستاویزات میں درج نہیں ہے۔ میں صرف تنظیم اساتذہ پاکستان کے دستور، تعارف، منصوبہ عمل، ذمہ داران، خواتین ونگ، رکنیت، نصاب اور ضابطہ اخلاق کے بارے میں بتا سکتا ہوں۔\n\nمزید معلومات کے لیے مرکزی دفتر سے رابطہ کریں:\nTAPofficial1969@gmail.com";

function getAnswer(rawQuery) {
  var q = (rawQuery || "").trim();
  if (!q) return "براہِ کرم اپنا سوال لکھیں۔";
  var nq = normalize(q);

  // 1) سلام / شکریہ / الوداع
  if (isGreeting(nq)) {
    return "وعلیکم السلام! میں تنظیم اساتذہ پاکستان کا معلوماتی اسسٹنٹ ہوں۔\n\nآپ مجھ سے تنظیم کے تعارف، دستور، منصوبہ عمل، ذمہ داران، خواتین ونگ، رکنیت، نصاب یا ضابطہ اخلاق کے بارے میں پوچھ سکتے ہیں۔";
  }
  if (isThanks(nq)) return "خوش آمدید! مزید کوئی سوال ہو تو ضرور پوچھیں۔";
  if (isBye(nq)) return "اللہ حافظ! تنظیم اساتذہ پاکستان کی خدمت میں حاضر رہوں گا۔";

  // 2) کسی فرد کا نام → ذاتی کارڈ
  var person = findPerson(nq);
  if (person) return personCard(person);

  // 3) صوبہ + صدر/ذمہ دار → متعلقہ صوبے کا صدر
  var prov = detectProvince(nq);
  if (prov && /(صدر|ذمہ دار|عہدیدار)/.test(nq)) {
    var sec = kbById(prov);
    if (sec) return sec.answer;
  }
  if (prov && prov !== "punjab") {
    // صرف صوبے کا نام لکھا ہو تو بھی اس کا صدر بتا دیں
    var onlyProv = tokens(nq).every(function (t) {
      return ["کا", "کی", "کے", "صوبہ", "میں"].indexOf(t) !== -1 ||
        PROVINCES.some(function (p) { return p.keys.some(function (k) { return normalize(k) === t; }); });
    });
    if (onlyProv) { var s2 = kbById(prov); if (s2) return s2.answer; }
  }

  // 4) عہدے کا نام → متعلقہ مرکزی ذمہ دار (لمبے عہدے پہلے)
  var ROLE_MAP = [
    { key: "سیکرٹری نشر و اشاعت", idx: 5 },
    { key: "سیکرٹری جنرل", idx: 2 },
    { key: "جوائنٹ سیکرٹری", idx: 3 },
    { key: "سیکرٹری مالیات", idx: 4 },
    { key: "نائب صدر", idx: 1 }
  ];
  for (var r = 0; r < ROLE_MAP.length; r++) {
    if (nq.indexOf(normalize(ROLE_MAP[r].key)) !== -1) return personCard(PEOPLE[ROLE_MAP[r].idx]);
  }

  // 5) اکیلا «صدر» → مرکزی صدر
  if (/(^|\s)صدر(\s|$)/.test(" " + nq + " ") && !prov) {
    return personCard(PEOPLE[0]);
  }

  // 6) کلیدی الفاظ کی اسکورنگ
  var best = null, bestScore = 0;
  for (var i = 0; i < KB.length; i++) {
    var sc = scoreSection(KB[i], nq);
    if (sc > bestScore) { bestScore = sc; best = KB[i]; }
  }
  if (best && bestScore >= 3) return best.answer;

  // 7) فال بیک — کبھی حقائق نہ گھڑیں
  return FALLBACK;
}

